function findDish(id) {
  return DISHES.filter(function (d) { return d.id === id; })[0] || null;
}

function groupsOf(cuisineId) {
  return GROUPS[cuisineId] || [];
}

function dishesOf(cuisineId, groupId) {
  return DISHES.filter(function (d) {
    if (d.cuisine !== cuisineId) return false;
    if (!groupId || groupId === 'all') return true;
    return d.group === groupId;
  });
}

function basesOf(cuisineId) {
  return DISHES.filter(function (d) {
    return d.cuisine === cuisineId && d.isBase === true;
  });
}

module.exports = { CUISINES, GROUPS, DISHES, findDish, groupsOf, dishesOf, basesOf };
